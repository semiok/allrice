import {
  skillSourceErrorHeader,
  type SkillSourceErrorReason,
} from '@allrice/contracts';
import { EmployeeContentError, PersonalSkillError } from '@allrice/database';
import { FileArchiveError } from '@allrice/file-archives';
import {
  PersonalSkillSourceError,
  SkillPreviewError,
} from '@allrice/skill-import';

/** Only typed server facts; never parse user text or return arbitrary errors. */
export function addSkillSourceErrorReason(
  response: Response,
  error: unknown,
  operation: 'preview' | 'confirm',
) {
  let reason: SkillSourceErrorReason | undefined;
  if (error instanceof SkillPreviewError) {
    reason =
      error.code === 'source_invalid'
        ? operation === 'preview'
          ? 'package_invalid'
          : 'preview_invalid'
        : error.code;
  } else if (error instanceof PersonalSkillSourceError) {
    reason =
      error.code === 'source_skill_missing'
        ? 'skill_missing'
        : 'source_unavailable';
  } else if (error instanceof EmployeeContentError) {
    if (error.code === 'workflow_invalid') reason = 'workflow_invalid';
    if (error.code === 'version_conflict' || error.code === 'request_conflict')
      reason = 'version_conflict';
  } else if (error instanceof PersonalSkillError) {
    if (error.code === 'source_invalid') reason = 'package_invalid';
    if (error.code === 'name_conflict' || error.code === 'limit')
      reason = error.code;
    if (error.code === 'conflict') reason = 'version_conflict';
  } else if (error instanceof FileArchiveError) {
    if (
      !['FILE_ARCHIVE_CANCELED', 'FILE_ARCHIVE_AUTHORITY_LOST'].includes(
        error.code,
      )
    )
      reason = operation === 'confirm' ? 'preview_invalid' : 'package_invalid';
  } else if (error instanceof Error) {
    // These identifiers are generated by the shared package inspector.
    if (error.message === 'personal_skill_package_missing_skill')
      reason = 'skill_missing';
    else if (
      [
        'personal_skill_package_unsafe_path',
        'personal_skill_package_path_conflict',
        'personal_skill_package_candidate_limit',
      ].includes(error.message)
    )
      reason = 'package_invalid';
  }
  if (reason) response.headers.set(skillSourceErrorHeader, reason);
  return response;
}
