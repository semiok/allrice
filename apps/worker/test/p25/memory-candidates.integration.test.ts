  it.each(['personal', 'checkpoint'] as const)(
    'replays the independent 069 V2 %s receipt without creating a second memory, revision or operation',
    async (kind) => {
      expect(sha256(request069[kind].json)).toBe(request069[kind].digest);
      const f = await setup(),
        old = await seedOperation069(f, kind);
      const before = await old.stored();
      expect(before).toMatchObject({
        memories: 1,
        revisions: 1,
        operations: 1,
      });
      const expected = kind === 'personal' ? old.personal : old.expected;
      expect(await old.replay()).toEqual(expected);
      expect(await old.replay()).toEqual(expected);
      expect(await old.stored()).toEqual(before);
    },
  );
  it.each(['pair', 'content', 'digest', 'scope', 'v1_request'] as const)(
    'rejects the existing checkpoint operation with %s mismatch and keeps its original rows',
    async (fault) => {
      const f = await setup(),
        old = await seedOperation069(f, 'checkpoint', fault);
      const before = await old.stored();
      if (fault === 'pair' || fault === 'v1_request')
        await expect(old.replay()).rejects.toMatchObject({
          details: { reason: 'idempotency_conflict' },
        });
      else
        await expect(old.replay()).rejects.toMatchObject({
          code: 'employee_memory_contract_changed',
        });
      expect(before).toMatchObject({
        memories: 1,
        revisions: 1,
        operations: 1,
      });
      expect(await old.stored()).toEqual(before);
    },
  );

